// MARK: - Community

@Suite("Community")
struct CommunityTests {
    private func report(
        _ state: WaterState, hoursAgo: Double, rating: Int? = nil, now: Date
    ) -> Report {
        Report(
            fountainID: "1", state: state, rating: rating,
            date: now.addingTimeInterval(-hoursAgo * 3600), author: "Visitante 0001"
        )
    }

    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    @Test("No reports means unknown, not running")
    func nothing() {
        #expect(CommunitySummary.summarising([], now: now) == .empty)
        #expect(CommunitySummary.empty.state == .unknown)
    }

    @Test("The newest fresh report decides the water")
    func newestWins() {
        let summary = CommunitySummary.summarising([
            report(.running, hoursAgo: 20, now: now),
            report(.dry, hoursAgo: 2, now: now),
        ], now: now)
        #expect(summary.state == .dry)
    }

    /// A fountain that was running last week says nothing about today.
    @Test("A stale report is not believed")
    func stale() {
        let summary = CommunitySummary.summarising([
            report(.running, hoursAgo: 80, rating: 5, now: now),
        ], now: now)
        #expect(summary.state == .unknown)
        #expect(summary.average == 5)
        #expect(summary.latestDate != nil)
    }

    @Test("Ratings average across every report that carries one")
    func average() {
        let summary = CommunitySummary.summarising([
            report(.running, hoursAgo: 1, rating: 5, now: now),
            report(.running, hoursAgo: 2, rating: 4, now: now),
            report(.running, hoursAgo: 3, now: now),
        ], now: now)
        #expect(summary.average == 4.5)
        #expect(summary.ratingCount == 2)
        #expect(summary.reportCount == 3)
    }

    @Test("A report clamps its rating and its note")
    func clamping() {
        let long = String(repeating: "a", count: 500)
        let made = Report(fountainID: "1", state: .running, rating: 9, note: "  \(long)  ", author: "x")
        #expect(made.rating == 5)
        #expect(made.note.count == Report.maximumNoteLength)
        #expect(Report(fountainID: "1", state: .dry, rating: 0, author: "x").rating == 1)
    }
}

// MARK: - Persistence

@Suite("Preferences", .serialized)
struct PreferencesTests {
    private static let suite = "br.tec.nuance.toret.tests"

    private func scratch() -> UserDefaults {
        UserDefaults.standard.removePersistentDomain(forName: Self.suite)
        return UserDefaults(suiteName: Self.suite)!
    }

    /// A first launch has no keys; a second launch that turned both switches off
    /// has them set to false. Reading with `bool(forKey:)` alone cannot tell the
    /// two apart, and would switch them back on every morning.
    @Test("An empty store is a first launch, not a store of falses")
    func firstLaunch() {
        let defaults = scratch()
        #expect(Preferences.load(from: defaults) == .initial)
    }

    @Test("Every decision survives a relaunch")
    func roundTrip() {
        let defaults = scratch()
        let preferences = Preferences(
            savedIDs: ["118", "455"],
            filters: [MapFilter.accessible.rawValue],
            compassAlwaysVisible: false,
            proximityAlerts: false,
            selectedID: "092"
        )
        preferences.save(to: defaults)
        #expect(Preferences.load(from: defaults) == preferences)
    }

    @Test("Switching everything off stays off")
    func switchesStayOff() {
        let defaults = scratch()
        var preferences = Preferences.initial
        preferences.compassAlwaysVisible = false
        preferences.proximityAlerts = false
        preferences.save(to: defaults)

        let restored = Preferences.load(from: defaults)
        #expect(!restored.compassAlwaysVisible)
        #expect(!restored.proximityAlerts)
    }
}

@Suite("Widget bridge", .serialized)
struct WidgetBridgeTests {
    private static let suite = "br.tec.nuance.toret.tests.widget"

    private func scratch() -> UserDefaults {
        UserDefaults.standard.removePersistentDomain(forName: Self.suite)
        return UserDefaults(suiteName: Self.suite)!
    }

    @Test("A published fix comes back")
    func publish() throws {
        let defaults = scratch()
        let castello = CLLocationCoordinate2D(latitude: 45.0709, longitude: 7.6858)
        WidgetBridge.publish(origin: castello, to: defaults)

        let read = try #require(WidgetBridge.origin(from: defaults))
        #expect(abs(read.latitude - castello.latitude) < 0.000001)
        #expect(abs(read.longitude - castello.longitude) < 0.000001)
    }

    @Test("Turning the compass off clears the fix")
    func clear() {
        let defaults = scratch()
        WidgetBridge.publish(origin: Catalogue.anchor, to: defaults)
        WidgetBridge.publish(origin: nil, to: defaults)
        #expect(WidgetBridge.origin(from: defaults) == nil)
    }

    /// A widget reading "84 m" from yesterday's walk is worse than one that
    /// admits it is showing the city centre.
    @Test("A stale fix is discarded rather than shown")
    func staleness() {
        let defaults = scratch()
        WidgetBridge.publish(origin: Catalogue.anchor, to: defaults)
        defaults.set(
            Date.now.timeIntervalSince1970 - WidgetBridge.freshness - 60,
            forKey: Store.Key.originDate
        )
        #expect(WidgetBridge.origin(from: defaults) == nil)
    }
}

// MARK: - Model

@Suite("Model")
@MainActor
struct ToretModelTests {
    /// A fountain that is not the nearest one from the anchor.
    static let farID = ToretModel(preferences: .initial).byDistance[40].id

    /// Reopening on the fountain that was showing is the difference between the
    /// app remembering a conversation and starting one over.
    @Test("The model reopens on the fountain that was showing")
    func restoresSelection() {
        var preferences = Preferences.initial
        preferences.selectedID = Self.farID
        let model = ToretModel(preferences: preferences)
        #expect(model.selected.id == Self.farID)
        #expect(model.needleAngle == model.selected.bearing)
    }

    @Test("With nothing remembered it opens on the nearest water")
    func opensOnNearest() {
        let model = ToretModel(preferences: .initial)
        #expect(model.selected.id == model.byDistance[0].id)
    }

    /// The bug this exists to prevent: `@Observable` fires `didSet` on the
    /// assignments in `init`, so the model wrote its preferences back before it
    /// had finished reading them — stamping the selection as whichever fountain
    /// happened to be first in the catalogue rather than the one you left open.
    @Test("Restoring never writes back over the store")
    func restoringDoesNotPersist() {
        let suite = "br.tec.nuance.toret.tests.model"
        UserDefaults.standard.removePersistentDomain(forName: suite)
        let defaults = UserDefaults(suiteName: suite)!

        var preferences = Preferences.initial
        preferences.selectedID = Self.farID
        preferences.save(to: defaults)

        _ = ToretModel(preferences: preferences, defaults: defaults)
        #expect(defaults.string(forKey: Store.Key.selected) == Self.farID)
    }

    /// The compass captions its figure "fonte mais próxima". Reopening on a
    /// remembered fountain, or walking past a nearer one, makes that caption
    /// false — so the model has to be able to say when it is.
    @Test("The model knows when the needle is not on the nearest fountain")
    func nearestClaim() {
        #expect(ToretModel(preferences: .initial).selectedIsNearest)

        var preferences = Preferences.initial
        preferences.selectedID = Self.farID
        let restored = ToretModel(preferences: preferences)
        #expect(restored.selected.id == Self.farID)
        #expect(!restored.selectedIsNearest)
    }

    @Test("Unknown filters and fountains are dropped, not crashed on")
    func toleratesStaleStore() {
        let preferences = Preferences(
            savedIDs: ["999"],
            filters: ["Filtro que não existe mais"],
            compassAlwaysVisible: true,
            proximityAlerts: true,
            selectedID: "999"
        )
        let model = ToretModel(preferences: preferences)
        #expect(model.activeFilters.isEmpty)
        #expect(model.savedFountains.isEmpty)
        #expect(model.selected.id == model.byDistance[0].id)
    }
}

