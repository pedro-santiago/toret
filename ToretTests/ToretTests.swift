/// The needle and every distance in the app rest on these four lines of
/// trigonometry, and a sign error in them is invisible until someone walks the
/// wrong way down Via Po.
@Suite("Bearings")
struct BearingTests {
    private let origin = CLLocationCoordinate2D(latitude: 45, longitude: 7)

    @Test("North is 0°, east is 90°")
    func cardinals() {
        let north = CLLocationCoordinate2D(latitude: 45.01, longitude: 7)
        let east = CLLocationCoordinate2D(latitude: 45, longitude: 7.01)
        #expect(abs(Bearing.forwardAzimuth(from: origin, to: north)) < 0.01)
        #expect(abs(Bearing.forwardAzimuth(from: origin, to: east) - 90) < 0.01)
    }

    @Test("The azimuth stays inside one turn")
    func wrapped() {
        let west = CLLocationCoordinate2D(latitude: 45, longitude: 6.99)
        let bearing = Bearing.forwardAzimuth(from: origin, to: west)
        #expect(bearing >= 0 && bearing < 360)
        #expect(abs(bearing - 270) < 0.01)
    }

    /// The bug this exists to prevent: interpolating 350 → 10 as numbers spins
    /// the needle 340° the wrong way round to travel 20.
    @Test("The needle takes the short way round")
    func shortWay() {
        #expect(Bearing.shortestDelta(from: 350, to: 10) == 20)
        #expect(Bearing.shortestDelta(from: 10, to: 350) == -20)
        #expect(Bearing.shortestDelta(from: 296, to: 8) == 72)
        #expect(abs(Bearing.shortestDelta(from: 0, to: 180)) == 180)
    }

    @Test("Separation is unsigned and never exceeds half a turn")
    func separation() {
        #expect(Bearing.separation(350, 10) == 20)
        #expect(Bearing.separation(10, 350) == 20)
        #expect(Bearing.separation(0, 200) == 160)
    }
}

// MARK: - Catalogue

@Suite("Catalogue")
struct CatalogueTests {
    /// The file is generated by `tools/build-catalogue.py`; if the bundle step
    /// drops it the app opens on an empty list, so say so here.
    @Test("The bundled catalogue is real and complete")
    func loads() {
        #expect(Catalogue.entries.count > 600)
        #expect(Set(Catalogue.entries.map(\.id)).count == Catalogue.entries.count)
        #expect(Catalogue.entries.contains { $0.kind == .toret })
    }

    @Test("Every point is inside the Turin municipality's box")
    func insideTurin() {
        for entry in Catalogue.entries {
            #expect((44.99...45.14).contains(entry.lat))
            #expect((7.57...7.78).contains(entry.lon))
        }
    }

    @Test("Most points can be named by a street or a place")
    func named() {
        let named = Catalogue.entries.filter { $0.name != nil || $0.street != nil }
        #expect(Double(named.count) / Double(Catalogue.entries.count) > 0.9)
    }

    @Test("The catalogue covers Turin and nowhere far from it")
    func coverage() {
        #expect(Catalogue.covers(Catalogue.anchor))
        #expect(Catalogue.covers(CLLocationCoordinate2D(latitude: 45.0, longitude: 7.65)))
        #expect(!Catalogue.covers(CLLocationCoordinate2D(latitude: -23.55, longitude: -46.63)))
    }
}

// MARK: - Fountains

private func entry(
    id: String = "1", kind: FountainKind = .fountain, name: String? = nil,
    street: String? = nil, zone: String? = nil,
    lat: Double = 45.0672, lon: Double = 7.6822
) -> CatalogueEntry {
    CatalogueEntry(
        id: id, lat: lat, lon: lon, kind: kind, name: name, street: street, zone: zone,
        ref: nil, wheelchair: nil, bottle: nil, dog: nil, seasonal: nil, checked: nil
    )
}

@Suite("Fountains")
struct FountainTests {
    @Test("Walking minutes never round to zero")
    func walkingPace() {
        let anchor = Catalogue.anchor
        let onTop = Fountain(
            entry: entry(lat: anchor.latitude, lon: anchor.longitude), from: anchor
        )
        #expect(onTop.distance == 0)
        #expect(onTop.walkingMinutes == 1)
    }

    @Test("Relocating re-measures without moving the fountain")
    func relocation() {
        let fountain = Fountain(entry: entry(), from: Catalogue.anchor)
        let moved = fountain.relocated(
            to: CLLocationCoordinate2D(latitude: 45.0709, longitude: 7.6858)
        )
        #expect(moved.latitude == fountain.latitude)
        #expect(moved.longitude == fountain.longitude)
        #expect(moved.distance != fountain.distance)
        #expect(moved.distance > 400)
        #expect(moved == fountain)
    }

    /// Turin names its squares and streets with the generic first, so the break
    /// belongs after it — "Corso / Vittorio Emanuele II", never "Corso Vittorio / Emanuele II".
    @Test("Place names break after the generic")
    func displayBreak() {
        let fountain = Fountain(
            entry: entry(street: "Corso Vittorio Emanuele II", zone: "Cenisia"),
            from: Catalogue.anchor
        )
        #expect(fountain.titleLines == "Corso\nVittorio Emanuele II")
        #expect(Fountain(entry: entry(name: "Superga"), from: Catalogue.anchor).titleLines == "Superga")
    }

    /// Mappers write "Toret" in the name field when they have nothing to say.
    /// That is a kind, not a name, and must not become the title.
    @Test("A generic name gives way to the street")
    func genericNames() {
        let generic = Fountain(
            entry: entry(kind: .toret, name: "Toret", street: "Via della Consolata", zone: "Aurora"),
            from: Catalogue.anchor
        )
        #expect(generic.place == "Via della Consolata")
        let named = Fountain(
            entry: entry(name: "Fontana dei Dodici Mesi", street: "Parco del Valentino"),
            from: Catalogue.anchor
        )
        #expect(named.place == "Fontana dei Dodici Mesi")
        #expect(named.addressLine == "Parco del Valentino")
    }

    @Test("Nothing to name it by still gives a title")
    func unnamed() {
        let bare = Fountain(entry: entry(kind: .toret), from: Catalogue.anchor)
        #expect(bare.place == "Toret")
        #expect(!bare.zone.isEmpty)
    }

    @Test("Identity is the OpenStreetMap id, not the measurement")
    func identity() {
        let a = Fountain(entry: entry(id: "7"), from: Catalogue.anchor)
        let b = a.with(community: CommunitySummary(
            state: .dry, latestDate: .now, average: 2, ratingCount: 1, reportCount: 1
        ))
        #expect(a == b)
        #expect(b.state == .dry)
        #expect(a.state == .unknown)
    }
}

